package com.shilapi.xcertplay.receiver

import java.security.MessageDigest
import java.util.UUID
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit

/** First-use consent and optional remembered sender identities, separate from media ownership. */
class ReceiverDeviceTrust(
    private val store: Store,
    private val diagnostic: (String) -> Unit = {},
    private val nowMillis: () -> Long = { System.nanoTime() / 1_000_000 },
) {
    interface Store {
        fun contains(fingerprint: String): Boolean
        fun remember(fingerprint: String)
        fun forgetAll()
    }

    sealed class Decision {
        object Allowed : Decision()
        object Denied : Decision()
        class Pending internal constructor(val id: String, internal val revision: Long,
                                           internal val fingerprint: String, internal val verified: Boolean,
                                           internal val persistentFingerprint: String,
                                           internal val finished: CountDownLatch = CountDownLatch(1)) : Decision() {
            @Volatile internal var allowed = false
        }
    }

    private data class Request(val decision: Decision.Pending, val fingerprint: String, val name: String,
                               val browser: String, val expires: Long, val verified: Boolean,
                               val mediaType: String, val sessionGroup: Pair<String, String>?,
                               val waitingConnections: MutableSet<String> = linkedSetOf())
    private var pending: Request? = null
    private var browser: String? = null
    private var browserSeenAt = Long.MIN_VALUE
    private var revision = 0L
    private val deniedUntil = linkedMapOf<String, Long>()
    // A connection may later present a different identity; its one-time grant must
    // remain bound to the identity that was actually approved.
    private val allowedConnections = linkedMapOf<String, String>()
    private val sessionGrants = linkedMapOf<Pair<String, String>, MutableSet<String>>()
    private var unverifiedDeniedUntil = 0L
    private var lastDiagnostic: String? = null
    private var lastDiagnosticAt = Long.MIN_VALUE

    /** Called only after authenticating the paired browser's `/control` request. */
    @Synchronized fun browserSeen(session: String) {
        if (browser != null && browser != session) cancelPending()
        browser = session
        browserSeenAt = nowMillis()
    }

    @Synchronized fun browserGone(session: String) {
        if (browser == session) {
            browser = null
            cancelPending()
        }
    }

    /** Does not claim media ownership; the receiver must separately exclude other active senders. */
    @Synchronized fun request(publicKey: ByteArray?, deviceName: String): Decision {
        val fingerprint = fingerprint(publicKey) ?: return Decision.Denied
        return requestIdentity(fingerprint, deviceName, verified = true)
    }

    /** The token must be generated by the receiver for this control connection, never taken from a client header. */
    @Synchronized fun requestOnce(sessionToken: String, deviceName: String): Decision {
        if (!validToken(sessionToken)) return Decision.Denied
        return requestIdentity("connection:$sessionToken", deviceName, verified = false)
    }

    /** One-time permission belongs to this receiver-generated connection, never to a name/IP.
     * The identity must be a signature-verified key or a normalized stable sender claim. */
    @Synchronized fun requestSession(sessionToken: String, publicKey: ByteArray?, deviceName: String,
                                     mediaType: String = "unknown", verifiedSessionId: String? = null): Decision {
        if (!validToken(sessionToken)) return Decision.Denied
        val key = fingerprint(publicKey)
        val sessionGroup = if (key != null && verifiedSessionId?.replace("-", "")?.matches(Regex("[A-Fa-f0-9]{32}")) == true)
            key to requireNotNull(verifiedSessionId).replace("-", "").lowercase() else null
        sessionGroup?.let { group ->
            sessionGrants[group]?.takeIf { it.isNotEmpty() }?.let { connections ->
                val connection = "connection:$sessionToken"
                connections.add(connection)
                while (connections.size > MAX_CONNECTION_GRANTS) connections.remove(connections.first())
                allowedConnections[connection] = group.first
                while (allowedConnections.size > MAX_CONNECTION_GRANTS) allowedConnections.remove(allowedConnections.keys.first())
                report("session-hit")
                return Decision.Allowed
            }
        }
        return requestIdentity("connection:$sessionToken", deviceName, key != null, key.orEmpty(), mediaType, sessionGroup)
    }

    private fun requestIdentity(fingerprint: String, deviceName: String, verified: Boolean,
                                persistentFingerprint: String = fingerprint, mediaType: String = "unknown",
                                sessionGroup: Pair<String, String>? = null): Decision {
        expire()
        if (verified && store.contains(persistentFingerprint)) {
            report("remembered-hit")
            return Decision.Allowed
        }
        if (allowedConnections[fingerprint] == if (verified) persistentFingerprint else "") {
            report("connection-hit")
            return Decision.Allowed
        }
        val now = nowMillis()
        if (!verified && now < unverifiedDeniedUntil) return Decision.Denied
        if (deniedUntil[if (verified) persistentFingerprint else fingerprint]?.let { now < it } == true) return Decision.Denied
        val activeBrowser = browser?.takeIf { now - browserSeenAt in 0..BROWSER_LIVE_MILLIS } ?: return Decision.Denied
        pending?.let { return if (it.fingerprint == fingerprint && it.browser == activeBrowser) it.decision else Decision.Denied }
        val name = deviceName.filter { !it.isISOControl() }.trim().take(80).ifEmpty { "AirPlay" }
        report(if (verified) "prompt-persistent" else "prompt-connection")
        return Decision.Pending(UUID.randomUUID().toString(), revision, fingerprint, verified, persistentFingerprint).also {
            pending = Request(it, fingerprint, name, activeBrowser, now + APPROVAL_MILLIS, verified,
                mediaType.takeIf { type -> type in setOf("audio", "mirror", "video", "photo") } ?: "unknown", sessionGroup)
        }
    }

    /** Waits only on the sender's control thread, bounded by the prompt's original expiry. */
    fun authorize(publicKey: ByteArray?, deviceName: String): Boolean = await(request(publicKey, deviceName))

    fun authorizeOnce(sessionToken: String, deviceName: String): Boolean = await(requestOnce(sessionToken, deviceName))

    fun authorizeSession(sessionToken: String, publicKey: ByteArray?, deviceName: String,
                         mediaType: String = "unknown", verifiedSessionId: String? = null): Boolean {
        val persistent = fingerprint(publicKey)
        val (other, decision) = synchronized(this) {
            expire()
            val existing = pending?.takeIf { persistent != null && it.verified &&
                it.decision.persistentFingerprint == persistent && it.fingerprint != "connection:$sessionToken" }
            if (existing != null && existing.sessionGroup != null &&
                existing.sessionGroup.second == verifiedSessionId?.replace("-", "")?.lowercase() && validToken(sessionToken)) {
                if (existing.waitingConnections.size < MAX_CONNECTION_GRANTS)
                    existing.waitingConnections.add("connection:$sessionToken")
            }
            existing to if (existing == null) requestSession(sessionToken, publicKey, deviceName, mediaType, verifiedSessionId) else null
        }
        if (other != null) {
            try {
                other.decision.finished.await((other.expires - nowMillis()).coerceIn(0, APPROVAL_MILLIS), TimeUnit.MILLISECONDS)
            } catch (_: InterruptedException) {
                Thread.currentThread().interrupt()
                return false
            }
        }
        return await(decision ?: requestSession(sessionToken, publicKey, deviceName, mediaType, verifiedSessionId))
    }

    private fun await(decision: Decision): Boolean = when (decision) {
        Decision.Allowed -> true
        Decision.Denied -> false
        is Decision.Pending -> {
            val remaining = synchronized(this) { pending?.takeIf { it.decision === decision }?.let { it.expires - nowMillis() } ?: 0L }
            try {
                decision.finished.await(remaining.coerceIn(0, APPROVAL_MILLIS), TimeUnit.MILLISECONDS)
            } catch (_: InterruptedException) {
                Thread.currentThread().interrupt()
            }
            synchronized(this) {
                if (pending?.decision === decision) cancelPending()
                decision.allowed && decision.revision == revision &&
                    ((decision.verified && store.contains(decision.persistentFingerprint)) ||
                        allowedConnections[decision.fingerprint] == if (decision.verified) decision.persistentFingerprint else "")
            }
        }
    }

    @Synchronized fun prompt(session: String): Map<String, Any?>? {
        expire()
        val request = pending?.takeIf { it.browser == session } ?: return null
        return mapOf("id" to request.decision.id, "name" to request.name,
            "verified" to request.verified, "mediaType" to request.mediaType,
            "remainingMillis" to (request.expires - nowMillis()).coerceIn(0, APPROVAL_MILLIS))
    }

    /** Late, replayed and replaced-browser responses can never establish trust. */
    @Synchronized fun respond(session: String, id: String, allow: Boolean, remember: Boolean = true): Boolean {
        expire()
        val request = pending?.takeIf { it.browser == session && it.decision.id == id } ?: return false
        if (allow) {
            if (remember && request.verified) {
                try {
                    store.remember(request.decision.persistentFingerprint)
                    report("remembered-saved")
                } catch (error: Exception) {
                    report("remembered-save-failed")
                    throw error
                }
            }
            else {
                allowedConnections[request.fingerprint] = if (request.verified) request.decision.persistentFingerprint else ""
                while (allowedConnections.size > MAX_CONNECTION_GRANTS) allowedConnections.remove(allowedConnections.keys.first())
                request.sessionGroup?.let { group ->
                    sessionGrants.getOrPut(group) { linkedSetOf() }.apply {
                        add(request.fingerprint)
                        addAll(request.waitingConnections)
                    }
                    while (sessionGrants.size > MAX_CONNECTION_GRANTS) sessionGrants.remove(sessionGrants.keys.first())
                }
                report(if (remember) "remember-unavailable" else "allowed-once")
            }
        } else report("rejected")
        request.decision.allowed = allow
        finish(request)
        return true
    }

    /** Revokes future connections without ending a cast that was already approved. */
    @Synchronized fun forgetAll() {
        revision++
        cancelPending()
        store.forgetAll()
        deniedUntil.clear()
        allowedConnections.clear()
        sessionGrants.clear()
        unverifiedDeniedUntil = 0
    }

    /** A connection-only grant dies with its originating protocol connection. */
    @Synchronized fun endSession(sessionToken: String) {
        val fingerprint = "connection:$sessionToken"
        allowedConnections.remove(fingerprint)
        pending?.waitingConnections?.remove(fingerprint)
        sessionGrants.entries.removeIf { entry -> entry.value.remove(fingerprint); entry.value.isEmpty() }
        pending?.takeIf { it.fingerprint == fingerprint }?.let(::finish)
    }

    @Synchronized fun close() {
        revision++
        browser = null
        cancelPending()
        allowedConnections.clear()
        sessionGrants.clear()
    }

    private fun expire() {
        val now = nowMillis()
        deniedUntil.entries.removeAll { now >= it.value }
        pending?.takeIf { now >= it.expires || browser != it.browser || now - browserSeenAt > BROWSER_LIVE_MILLIS }
            ?.let(::finish)
    }

    private fun cancelPending() { pending?.let(::finish) }

    private fun report(event: String) {
        val now = nowMillis()
        if (event == lastDiagnostic && now - lastDiagnosticAt in 0L until 5_000L) return
        lastDiagnostic = event
        lastDiagnosticAt = now
        runCatching { diagnostic("AirPlay trust: event=$event") }
    }

    private fun finish(request: Request) {
        if (!request.decision.allowed) {
            deniedUntil[if (request.verified) request.decision.persistentFingerprint else request.fingerprint] =
                nowMillis() + DENIAL_COOLDOWN_MILLIS
            while (deniedUntil.size > MAX_DENIALS) deniedUntil.remove(deniedUntil.keys.first())
            if (!request.verified) unverifiedDeniedUntil = nowMillis() + DENIAL_COOLDOWN_MILLIS
        }
        pending = null
        request.decision.finished.countDown()
    }

    companion object {
        const val APPROVAL_MILLIS = 5_000L
        const val BROWSER_LIVE_MILLIS = 3_000L
        const val DENIAL_COOLDOWN_MILLIS = 30_000L
        private const val MAX_DENIALS = 64
        private const val MAX_CONNECTION_GRANTS = 128
        private fun validToken(token: String) = token.length in 16..128 && token.all { it in '!'..'~' }

        fun fingerprint(publicKey: ByteArray?): String? = publicKey?.takeIf { it.size == 32 }?.let {
            MessageDigest.getInstance("SHA-256").digest(it).joinToString("") { value -> "%02x".format(value.toInt() and 0xff) }
        }
    }
}
